#!/usr/bin/env node
// Regenerates the architecture diagram in README.md from the AppHost model, so it cannot drift from apphost.cs.
//
//   node scripts/gen-architecture.mjs                  # builds the Aspire manifest from apphost.cs, then updates README
//   node scripts/gen-architecture.mjs manifest.json    # uses an existing manifest
//
// Nodes are the manifest's resources (parameters left out); edges are the references between them, found in each
// resource's environment and connection string ({name.bindings...}, {name.connectionString}). CI runs this and
// commits the result on main (.github/workflows/ci.yml, job "architecture").
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readmePath = join(root, 'README.md');
const START = '<!-- architecture:start -->';
const END = '<!-- architecture:end -->';

function loadManifest(path) {
  if (path) return { manifest: JSON.parse(readFileSync(path, 'utf8')), dir: dirname(resolve(path)) };
  const dir = mkdtempSync(join(tmpdir(), 'aspire-manifest-'));
  try {
    const out = join(dir, 'manifest.json');
    // AspireUseCliBundle=false: run the AppHost itself instead of handing off to `aspire run`, which would stop a
    // running instance of this AppHost.
    const args = ['run', '--file', 'apphost.cs', '-p:AspireUseCliBundle=false'];
    execFileSync('dotnet', [...args, '--', '--publisher', 'manifest', '--output-path', out], {
      cwd: root,
      stdio: ['ignore', 'ignore', 'inherit'],
    });
    return { manifest: JSON.parse(readFileSync(out, 'utf8')), dir };
  } finally {
    rmSync(dir, { recursive: true, force: true }); // paths in the manifest only need to resolve, not exist
  }
}

const { manifest, dir } = loadManifest(process.argv[2]);
const resources = Object.entries(manifest.resources).filter(
  ([, r]) => !r.type.startsWith('parameter') && r.type !== 'annotated.string',
);
const names = new Set(resources.map(([name]) => name));
const id = (name) => name.replace(/[^A-Za-z0-9_]/g, '_');
const repoPath = (path) => relative(root, resolve(dir, path));

function node(name, r) {
  const shape = (label) =>
    r.type === 'value.v0' || (r.type.startsWith('container') && r.connectionString)
      ? `[("${label}")]` // data stores and databases
      : `["${label}"]`;
  const detail =
    r.type === 'project.v0' ? `.NET project<br/>${repoPath(r.path)}`
    : r.build ? `built container<br/>${repoPath(r.build.context)}`
    : r.image ? `container<br/>${r.image}`
    : r.type === 'value.v0' ? 'database'
    : r.type;
  return `${id(name)}${shape(`<b>${name}</b><br/>${detail}`)}`;
}

// Aspire also injects NAME_HOST, NAME_URI, ... per connection string / service reference; those add nothing.
function edges(name, r) {
  const refs = new Map(); // target -> labels
  const add = (target, label) => {
    if (target === name || !names.has(target)) return;
    if (!refs.has(target)) refs.set(target, new Set());
    if (label) refs.get(target).add(label);
  };
  const env = Object.entries(r.env ?? {});
  const injected = env
    .map(([key]) => /^(?:ConnectionStrings|services)__([^_]+)/.exec(key)?.[1])
    .filter(Boolean)
    .map((n) => `${n.toUpperCase().replace(/-/g, '_')}_`);
  for (const [key, value] of env) {
    if (injected.some((prefix) => key.startsWith(prefix))) continue;
    const label = key.startsWith('services__')
      ? 'service discovery'
      : key.replace(/^ConnectionStrings__/, 'connection string: ').replace(/__/g, ':');
    for (const [, target] of String(value).matchAll(/\{([^.}]+)\./g)) add(target, label);
  }
  for (const [, target] of String(r.connectionString ?? '').matchAll(/\{([^.}]+)\./g)) add(target, null);
  return [...refs].map(([target, labels]) =>
    labels.size ? `${id(name)} -- "${[...labels].sort().join('<br/>')}" --> ${id(target)}` : `${id(name)} --> ${id(target)}`,
  );
}

const external = resources.filter(([, r]) => Object.values(r.bindings ?? {}).some((b) => b.external));
const lines = [
  'flowchart LR',
  '    browser([Browser])',
  '',
  '    subgraph apphost[Aspire AppHost - apphost.cs]',
  ...resources.map(([name, r]) => `        ${node(name, r)}`),
  '    end',
  '',
  ...external.map(([name]) => `    browser -.-> ${id(name)}`),
  ...resources.flatMap(([name, r]) => edges(name, r)).map((e) => `    ${e}`),
];

const block = [
  START,
  '<!-- Generated by scripts/gen-architecture.mjs from the Aspire manifest; do not edit by hand. -->',
  '',
  '```mermaid',
  ...lines,
  '```',
  '',
  END,
].join('\n');

const readme = readFileSync(readmePath, 'utf8');
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start < 0 || end < start) throw new Error(`README.md needs ${START} and ${END} markers`);
const updated = readme.slice(0, start) + block + readme.slice(end + END.length);
if (updated !== readme) writeFileSync(readmePath, updated);
console.log(updated === readme ? 'Architecture diagram is up to date.' : 'Updated the architecture diagram in README.md.');
